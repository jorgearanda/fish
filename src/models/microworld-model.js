'use strict';

var mongoose = require('mongoose');

var Schema = mongoose.Schema;
var ObjectId = Schema.ObjectId;

var microworldSchema = new Schema({
  name: {
    type: String,
    unique: true,
  },
  experimenter: {
    _id: ObjectId,
    username: String,
  },
  code: String,
  desc: String,
  status: String,
  dateCreated: Date,
  dateActive: Date,
  dateArchived: Date,
  numCompleted: Number,
  numAborted: Number,
  params: {
    numFishers: Number,
    numHumans: Number,
    numSeasons: Number,
    seasonDuration: Number,
    initialDelay: Number,
    seasonDelay: Number,
    enableEarlyEnd: Boolean,
    enablePause: Boolean,
    enableTutorial: Boolean,
    catchIntentionsEnabled: Boolean,
    catchIntentSeasons: [Number],
    catchIntentPrompt1: String,
    catchIntentPrompt2: String,
    catchIntentDialogDuration: Number,
    fisherClassesEnabled: Boolean,
    fisherClasses: [String],
    fisherClassCounts: Object,
    fisherClassEmojis: Object,
    fisherAdvantageEnabled: Boolean,
    fishValuePayGap: Number,
    costCastReduction: Number,
    costDepartureReduction: Number,
    costSecondReduction: Number,
    advantageEmoji: String,
    disadvantageEmoji: String,
    redirectURL: String,
    cleanAbortEnabled: Boolean,
    readRulesTimeout: { type: Number, default: 0 },
    lobbyWaitTimeout: { type: Number, default: 0 },
    promptTimeout: { type: Number, default: 20 },
    abortUrl: String,
    abortReadingRulesText: String,
    abortLobbyWaitText: String,
    forceAbortText: String,
    maxTimeouts: { type: Number, default: 10 },
    enableRespawnWarning: Boolean,
    hideOcean: { type: Boolean, default: false },
    showFishValueNotice: { type: Boolean, default: true }, // "Each fish earns you ..."
    showGameClock: { type: Boolean, default: false }, // time left in the season/break, in the status bar
    // Disconnect handling; when off, a fisher who drops mid-game is removed at once
    disconnectHandlingEnabled: { type: Boolean, default: false },
    disconnectGracePeriod: { type: Number, default: 30 }, // seconds to reconnect
    disconnectDuringGrace: { type: String, enum: ['pause', 'continue'], default: 'pause' },
    disconnectsAllowed: { type: Number, default: 3 }, // per fisher
    disconnectLostAction: { type: String, enum: ['end', 'remove'], default: 'end' },
    fishValue: Number,
    profitSeasonDisabled: Boolean,
    profitTotalDisabled: Boolean,
    profitGapDisabled: { type: Boolean, default: true },
    costDeparture: Number,
    costSecond: Number,
    costCast: Number,
    currencySymbol: String,
    certainFish: Number,
    availableMysteryFish: Number,
    reportedMysteryFish: Number,
    maxFish: Number,
    spawnFactor: Number,
    chanceCatch: Number,
    showFishers: Boolean,
    showFisherNames: Boolean,
    showFisherStatus: Boolean,
    showNumCaught: Boolean,
    showFisherBalance: Boolean,
    preparationText: String,
    endDepletionText: String,
    endTimeText: String,
    bots: [
      {
        name: String,
        greed: Number,
        greedSpread: Number,
        trend: String,
        predictability: String,
        probAction: Number,
        attemptsSecond: Number,
        fClass: String,
        fHasAdvantage: Boolean,
      },
    ],
    oceanOrder: String,
  },
});

exports.Microworld = mongoose.model('Microworld', microworldSchema);
